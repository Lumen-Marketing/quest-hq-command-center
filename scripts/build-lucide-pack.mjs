// Build the Lucide icon pack: a subset font plus the overrides that repoint this app's
// existing `ti-*` classes at Lucide glyphs.
//
//   npm run build:icons        (runs this after the Tabler subset)
//
// The app writes Tabler class names everywhere — `<i class="ti ti-home">`. Rather than
// touch 374 call sites, the pack is a stylesheet that overrides `content` and
// `font-family` for those same classes under [data-icon-pack="lucide"]. Selecting a pack
// therefore changes no markup and no JavaScript.
//
// Names are resolved three ways, in order:
//   1. the same name exists in Lucide          (58% of them)
//   2. scripts/lucide-aliases.mjs translates it (Tabler `device-desktop` = Lucide `monitor`)
//   3. neither                                 -> the icon KEEPS its Tabler glyph
//
// Case 3 is deliberate. A few mixed icons are much better than a confidently wrong one:
// `ladder` has no Lucide equivalent, and substituting something ladder-ish would mislabel
// a control. Those fall through to the Tabler rules already in the cascade.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { loadUsedIcons } from './icon-usage.mjs';
import { LUCIDE_ALIASES } from './lucide-aliases.mjs';

const SRC_TTF = 'node_modules/lucide-static/font/lucide.ttf';
const CODEPOINTS = 'node_modules/lucide-static/font/codepoints.json';
const OUT_FONT = 'src/assets/fonts/lucide-subset.woff2';
const OUT_CSS = 'src/lucide-icons.css';
const TMP = 'src/assets/fonts/.lucide-codepoints.tmp';

const lucide = JSON.parse(readFileSync(CODEPOINTS, 'utf8'));
const { used } = loadUsedIcons();

// Validate the alias table before anything else: a typo here would ship a blank box.
const badAliases = Object.entries(LUCIDE_ALIASES).filter(([, target]) => target && !(target in lucide));
if (badAliases.length) {
  console.error('Refusing to build: alias targets that Lucide does not define.');
  for (const [from, to] of badAliases) console.error(`  ${from} -> ${to}`);
  process.exit(1);
}

// Lucide is a single-weight outline set with no filled forms, so a Tabler `-filled` name
// resolves to the plain glyph.
const resolve = (name) => {
  if (name in LUCIDE_ALIASES) return LUCIDE_ALIASES[name] || null;
  const plain = name.replace(/-filled$/, '');
  if (plain in LUCIDE_ALIASES) return LUCIDE_ALIASES[plain] || null;
  if (plain in lucide) return plain;
  return null;
};

const mapped = [];
const unmapped = [];
for (const tablerName of [...used.keys()].sort()) {
  const target = resolve(tablerName);
  if (target) mapped.push([tablerName, target]);
  else unmapped.push(tablerName);
}

// One codepoint per distinct Lucide glyph; several Tabler names can share one.
const codepoints = [...new Set(mapped.map(([, target]) => lucide[target]))].sort((a, b) => a - b);

mkdirSync('src/assets/fonts', { recursive: true });
writeFileSync(TMP, codepoints.map((c) => c.toString(16)).join('\n'));
try {
  execFileSync('python', ['scripts/subset-font.py', SRC_TTF, TMP, OUT_FONT], { stdio: 'inherit' });
} finally {
  rmSync(TMP, { force: true });
}

const rules = mapped
  .map(([tablerName, target]) => `[data-icon-pack="lucide"] .ti-${tablerName}:before{content:"\\${lucide[target].toString(16)}"}`)
  .join('\n');

writeFileSync(OUT_CSS, `/* GENERATED by scripts/build-lucide-pack.mjs — do not edit by hand.
 * ${mapped.length} of ${used.size} icons repointed at Lucide; ${unmapped.length} keep their
 * Tabler glyph because Lucide has no equivalent. Run \`npm run build:icons\` to regenerate.
 *
 * Loaded only when the Lucide pack is selected, so the default costs nothing. */
@font-face {
  font-family: "lucide-icons";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("./assets/fonts/lucide-subset.woff2") format("woff2");
}

/* The family switch is separate from the per-icon content rules: icons with no Lucide
   equivalent must NOT match this, or they would render a blank box in the wrong font. */
${mapped.map(([n]) => `[data-icon-pack="lucide"] .ti-${n}`).join(',\n')} {
  font-family: "lucide-icons" !important;
}

${rules}
`);

const src = statSync(SRC_TTF).size;
const out = statSync(OUT_FONT).size;
console.log(`\nlucide: ${mapped.length} icons mapped, ${unmapped.length} keep Tabler`);
console.log(`woff2:  ${(src / 1024).toFixed(0)} KB ttf -> ${(out / 1024).toFixed(0)} KB subset`);
if (unmapped.length) console.log(`kept as Tabler: ${unmapped.join(' ')}`);
