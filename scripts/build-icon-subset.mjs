// Generate a Tabler icon font containing ONLY the icons this app references.
//
// The upstream font ships 5,340 glyphs (818 KB woff2) and we use ~340 of them —
// and it was loaded render-blocking from the legacy taskmanagement/ vendor path.
// This emits a subset font + a matching stylesheet into src/, so Vite hashes and
// bundles them like any other asset.
//
//   npm run build:icons
//
// tests/icon-subset.test.mjs fails if source references an icon the subset lacks,
// so adding a new `ti-*` to the app without re-running this cannot ship silently.

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, statSync, rmSync } from 'node:fs';
import { loadUsedIcons } from './icon-usage.mjs';

const SRC_TTF = 'taskmanagement/vendor/tabler-icons/fonts/tabler-icons.ttf';
const OUT_FONT = 'src/assets/fonts/tabler-icons-subset.woff2';
const OUT_CSS = 'src/tabler-icons.css';
const TMP_CODEPOINTS = 'src/assets/fonts/.codepoints.tmp';

const { fontMap, used, unknown, dynamic } = loadUsedIcons();

if (dynamic.size) {
  console.error('Refusing to build: icon names that cannot be resolved statically.');
  for (const d of dynamic) console.error('  ' + d);
  console.error('Subsetting would risk dropping a glyph the app renders at runtime.');
  process.exit(1);
}

mkdirSync('src/assets/fonts', { recursive: true });

const names = [...used.keys()].sort();
writeFileSync(TMP_CODEPOINTS, names.map((n) => used.get(n).toString(16)).join('\n'));

try {
  execFileSync('python', ['scripts/subset-font.py', SRC_TTF, TMP_CODEPOINTS, OUT_FONT], {
    stdio: 'inherit',
  });
} finally {
  rmSync(TMP_CODEPOINTS, { force: true });
}

const rules = names.map((n) => `.ti-${n}:before{content:"\\${used.get(n).toString(16)}"}`).join('\n');

writeFileSync(OUT_CSS, `/* GENERATED by scripts/build-icon-subset.mjs — do not edit by hand.
 * ${names.length} of ${fontMap.size} Tabler icons; run \`npm run build:icons\` to regenerate. */
@font-face {
  font-family: "tabler-icons";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("./assets/fonts/tabler-icons-subset.woff2") format("woff2");
}
.ti {
  font-family: "tabler-icons" !important;
  speak: none;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${rules}
`);

const before = statSync('taskmanagement/vendor/tabler-icons/fonts/tabler-icons.woff2').size;
const after = statSync(OUT_FONT).size;
const pct = (100 * (1 - after / before)).toFixed(1);

console.log(`\nicons:  ${names.length} kept / ${fontMap.size} in upstream font`);
console.log(`woff2:  ${(before / 1024).toFixed(0)} KB -> ${(after / 1024).toFixed(0)} KB  (-${pct}%)`);
if (unknown.size) {
  console.log(`\nNOTE: referenced but absent from the font (these render as blank boxes today):`);
  for (const n of [...unknown].sort()) console.log(`  ti-${n}`);
}
