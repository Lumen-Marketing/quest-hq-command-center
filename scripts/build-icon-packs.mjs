// Build every selectable icon pack: a subset font and a stylesheet per pack.
//
//   npm run build:icons     (runs after the Tabler subset)
//
// The app writes Tabler class names in 374 places — `<i class="ti ti-home">`. A pack does
// not touch any of them: it is a generated stylesheet that overrides `content` and
// `font-family` for those same classes under [data-icon-pack="<id>"]. Choosing a pack
// therefore changes no markup and no JavaScript.
//
// Packs are declared in icon-packs.config.mjs. Adding one is a table plus an entry there.

import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { loadUsedIcons } from './icon-usage.mjs';
import { ICON_PACKS, resolveGlyph } from './icon-packs.config.mjs';

const { used } = loadUsedIcons();
const appIcons = [...used.keys()].sort();
mkdirSync('src/assets/fonts', { recursive: true });

for (const pack of ICON_PACKS) {
  const glyphs = pack.glyphs();

  // A typo in an alias table would ship a blank box, so every declared target is checked
  // before anything is generated.
  const badAliases = Object.entries(pack.aliases)
    .filter(([, target]) => target && !pack.lookup(glyphs, target));
  if (badAliases.length) {
    console.error(`Refusing to build ${pack.id}: alias targets it does not define.`);
    for (const [from, to] of badAliases) console.error(`  ${from} -> ${to}`);
    process.exit(1);
  }

  const mapped = [];
  const kept = [];
  for (const name of appIcons) {
    const cp = resolveGlyph(pack, glyphs, name);
    if (cp) mapped.push([name, cp]);
    else kept.push(name);
  }

  const codepoints = [...new Set(mapped.map(([, cp]) => cp))].sort((a, b) => a - b);
  const tmp = `${pack.outFont}.codepoints.tmp`;
  writeFileSync(tmp, codepoints.map((c) => c.toString(16)).join('\n'));
  try {
    execFileSync('python', ['scripts/subset-font.py', pack.ttf, tmp, pack.outFont], { stdio: 'inherit' });
  } finally {
    rmSync(tmp, { force: true });
  }

  const scope = `[data-icon-pack="${pack.id}"]`;
  // The family switch lists ONLY the mapped icons. Applying it to everything would put a
  // Tabler codepoint in this font for the unmapped ones, which renders a blank box.
  const family = mapped.map(([name]) => `${scope} .ti-${name}`).join(',\n');
  const rules = mapped
    .map(([name, cp]) => `${scope} .ti-${name}:before{content:"\\${cp.toString(16)}"}`)
    .join('\n');

  writeFileSync(pack.outCss, `/* GENERATED by scripts/build-icon-packs.mjs — do not edit by hand.
 * ${pack.label}: ${mapped.length} of ${appIcons.length} icons repointed;${kept.length ? ` ${kept.length} keep their Tabler
 * glyph because ${pack.label} has no equivalent (${kept.join(', ')}).` : ' every icon has an equivalent.'}
 * Run \`npm run build:icons\` to regenerate.
 *
 * Loaded only when this pack is selected, so it costs nothing by default. */
@font-face {
  font-family: "${pack.fontFamily}";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("./assets/fonts/${pack.outFont.split('/').pop()}") format("woff2");
}

${family} {
  font-family: "${pack.fontFamily}" !important;
}

${rules}
`);

  const kb = (statSync(pack.outFont).size / 1024).toFixed(0);
  console.log(`${pack.label.padEnd(9)} ${mapped.length}/${appIcons.length} mapped, ${kb} KB woff2${kept.length ? `, keeps Tabler: ${kept.join(' ')}` : ''}`);
}
